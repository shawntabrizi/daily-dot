/**
 * Daily Word's guess list: every six-letter word in ENABLE (public domain),
 * SCOWL size 70 (`shared/sources/scowl-70-us.txt`, lowercase entries only) or
 * the answer list (`shared/wordlists/core.json`), bundled as the lazily
 * loaded chunk `app/src/games/word/guesses/6.ts`. Permissive on purpose:
 * a player must not be told a real word is not a word.
 *
 * Usage: pnpm generate:guesses -- /path/to/enable1.txt
 * (ENABLE is not committed; https://www.wordgamedictionary.com/enable/ or
 * the copy in `dolph/dictionary` on GitHub.)
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { validateWordlistFile, WORD_LENGTH } from "./content-validation";
import { sixLetterWords } from "./generate-wordlists";

function modulePath(relative: string): string {
  return fileURLToPath(new URL(relative, import.meta.url));
}

const enablePath = process.argv.filter((arg) => arg !== "--")[2];
if (!enablePath) {
  throw new Error("Usage: generate-guesses <path to enable1.txt>");
}
const [enableText, scowlText, answersText] = await Promise.all([
  readFile(enablePath, "utf8"),
  readFile(modulePath("../../shared/sources/scowl-70-us.txt"), "utf8"),
  readFile(modulePath("../../shared/wordlists/core.json"), "utf8"),
]);
const answers = validateWordlistFile(JSON.parse(answersText), "core.json").words;
const list = [
  ...new Set([
    ...sixLetterWords(enableText),
    ...sixLetterWords(scowlText),
    ...answers,
  ]),
].sort();

const target = modulePath(`../src/games/word/guesses/${WORD_LENGTH}.ts`);
await writeFile(
  target,
  `// Generated by scripts/generate-guesses.ts from ENABLE (public domain), SCOWL-70\n`
    + `// (ESDB, see shared/sources/README.md) and shared/wordlists/core.json. Do not edit.\n`
    + `// ${list.length} ${WORD_LENGTH}-letter words.\n`
    + `export default ${JSON.stringify(list.join(" "))};\n`,
);
console.log(`${WORD_LENGTH}: ${list.length} words -> ${target}`);
